export const NORMALIZE_HEADER = (h: string) =>
  h?.toString()
    .replace(/^\uFEFF/, '') // strip BOM
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '') // remove accents
    .toLowerCase()
    .trim()
    .replace(/[^\w]+/g, '_'); // spaces/punct → underscore

