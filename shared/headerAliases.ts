export const REQUIRED_FIELDS: Record<FileType, string[]> = {
  CLIENTES: ['codigo_cliente', 'nome'],
  VENDEDORES: ['codigo_vendedor', 'nome'],
  PRODUTOS: ['codigo_produto', 'descricao'],
  MOVIMENTACOES: ['data', 'codigo_produto', 'codigo_cliente', 'quantidade'],
  ESTOQUE: ['codigo_produto', 'quantidade', 'data_estoque'],
};

export function canonicalizeHeader(file: FileType, raw: string): string | null {
  const norm = NORMALIZE_HEADER(raw);
  return HEADER_ALIAS_MAP[file]?.[norm] ?? null;
}
